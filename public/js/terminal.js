const term = new Terminal({ cursorBlink:true, fontSize:14, convertEol:true, theme:{ background:'#0a0a0a', foreground:'#f5f5f5' } });
term.open(document.getElementById('terminal'));
const protocol = location.protocol === 'https:' ? 'wss' : 'ws';
const ws = new WebSocket(`${protocol}://${location.host}/ws/terminal`);
ws.onopen = () => term.write('\r\n');
ws.onmessage = (e) => term.write(e.data);
ws.onclose = () => term.write('\r\nСоединение закрыто.\r\n');
ws.onerror = () => term.write('\r\nОшибка соединения.\r\n');
term.onData((data) => ws.send(JSON.stringify({ type:'input', data })));
window.addEventListener('resize', () => ws.readyState===1 && ws.send(JSON.stringify({ type:'resize', cols: term.cols, rows: term.rows })));
