const term = new Terminal({ cursorBlink:true, fontSize:14, convertEol:true });
term.open(document.getElementById('terminal'));
term.write('Подключение к терминалу...\r\n');
const protocol = location.protocol === 'https:' ? 'wss' : 'ws';
const ws = new WebSocket(`${protocol}://${location.host}/ws/terminal`);
ws.onopen = () => term.write('Соединение установлено.\r\n');
ws.onmessage = e => term.write(e.data);
ws.onclose = () => term.write('\r\nСоединение закрыто.\r\n');
ws.onerror = () => term.write('\r\nОшибка соединения.\r\n');
term.onData(data => { if (ws.readyState === 1) ws.send(JSON.stringify({ type:'input', data })); });
window.addEventListener('resize', ()=>{ if (ws.readyState===1) ws.send(JSON.stringify({ type:'resize', cols:term.cols, rows:term.rows })); });
